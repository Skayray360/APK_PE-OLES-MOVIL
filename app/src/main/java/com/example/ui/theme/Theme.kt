object PenolesThemeExtras {
    val semanticColors: PenolesSemanticColors
        @Composable
        @ReadOnlyComposable
        get() = LocalPenolesSemanticColors.current
}

@Composable
fun PenolesConectaTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    // Color dinámico desactivado intencionalmente para preservar la identidad corporativa
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme
    val semanticColors = if (darkTheme) DarkSemanticColors else LightSemanticColors

    CompositionLocalProvider(LocalPenolesSemanticColors provides semanticColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            shapes = PenolesShapes,
            content = content
        )
    }
}
